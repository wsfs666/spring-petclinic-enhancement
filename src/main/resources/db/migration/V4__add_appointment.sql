-- 1. Create appointment slots first
CREATE TABLE appointment_slots (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    start_at TIMESTAMP NOT NULL,
    end_at TIMESTAMP NOT NULL,

    CONSTRAINT chk_slot_duration
        CHECK (end_at = start_at + INTERVAL '30 minutes'),

    CONSTRAINT uq_slot_start
        UNIQUE (start_at)
);

-- 2. Create appointments
CREATE TABLE appointments (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    pet_id INT NOT NULL REFERENCES pets(id),
    slot_id INT NOT NULL REFERENCES appointment_slots(id),

    status VARCHAR(20) NOT NULL DEFAULT 'CONFIRMED',

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_appointment_status
        CHECK (status IN ('CONFIRMED'))
);

-- 3. Prevent double booking
CREATE UNIQUE INDEX uq_confirmed_appointment_slot
ON appointments (slot_id)
WHERE status = 'CONFIRMED';